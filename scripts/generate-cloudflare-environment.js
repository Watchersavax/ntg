const fs = require('fs');
const path = require('path');

const outputPath = path.resolve(
  __dirname,
  '..',
  'src',
  'environments',
  'environment.cloudflare.ts'
);

function required(name) {
  const value = process.env[name];

  if (!value) {
    console.error('Missing required environment variable: ' + name);
    process.exit(1);
  }

  return value;
}

function optional(name) {
  return process.env[name] || '';
}

function booleanValue(name, defaultValue) {
  const value = process.env[name];

  if (value === undefined || value === '') {
    return defaultValue;
  }

  return value === 'true';
}

function withTrailingSlash(value) {
  if (!value || value[value.length - 1] === '/') {
    return value;
  }

  return value + '/';
}

const environment = {
  production: booleanValue('PRODUCTION', true),
  url: withTrailingSlash(required('API_URL')),
  publicKey: optional('FLUTTERWAVE_PUBLIC_KEY'),
  isAppointmentProduction: booleanValue('IS_APPOINTMENT_PRODUCTION', true)
};

const output = [
  '// This file is generated by scripts/generate-cloudflare-environment.js.',
  '// Do not edit it directly.',
  '',
  'export const environment = ' + JSON.stringify(environment, null, 2) + ';',
  ''
].join('\n');

fs.writeFileSync(outputPath, output);

console.log('Generated src/environments/environment.cloudflare.ts');
